-- SQLite teaching fixture: explicit NOT NULL on text/composite primary keys.
PRAGMA foreign_keys = ON;
CREATE TABLE DEPARTMENT (
 Dname TEXT NOT NULL UNIQUE, Dnumber INTEGER PRIMARY KEY,
 Mgr_ssn TEXT UNIQUE, Mgr_start_date TEXT,
 FOREIGN KEY (Mgr_ssn) REFERENCES EMPLOYEE(Ssn) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE EMPLOYEE (
 Fname TEXT NOT NULL, Minit TEXT, Lname TEXT NOT NULL,
 Ssn TEXT NOT NULL PRIMARY KEY, Bdate TEXT, Address TEXT, Sex TEXT,
 Salary REAL CHECK (Salary >= 0), Super_ssn TEXT, Dno INTEGER NOT NULL,
 FOREIGN KEY (Super_ssn) REFERENCES EMPLOYEE(Ssn) DEFERRABLE INITIALLY DEFERRED,
 FOREIGN KEY (Dno) REFERENCES DEPARTMENT(Dnumber) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE DEPT_LOCATIONS (
 Dnumber INTEGER NOT NULL, Dlocation TEXT NOT NULL,
 PRIMARY KEY (Dnumber, Dlocation),
 FOREIGN KEY (Dnumber) REFERENCES DEPARTMENT(Dnumber) ON DELETE CASCADE
);
CREATE TABLE PROJECT (
 Pname TEXT NOT NULL UNIQUE, Pnumber INTEGER PRIMARY KEY,
 Plocation TEXT, Dnum INTEGER NOT NULL,
 FOREIGN KEY (Dnum) REFERENCES DEPARTMENT(Dnumber)
);
CREATE TABLE WORKS_ON (
 Essn TEXT NOT NULL, Pno INTEGER NOT NULL,
 Hours REAL CHECK (Hours >= 0 AND Hours <= 168),
 PRIMARY KEY (Essn, Pno),
 FOREIGN KEY (Essn) REFERENCES EMPLOYEE(Ssn) ON DELETE CASCADE,
 FOREIGN KEY (Pno) REFERENCES PROJECT(Pnumber) ON DELETE CASCADE
);
CREATE TABLE DEPENDENT (
 Essn TEXT NOT NULL, Dependent_name TEXT NOT NULL,
 Sex TEXT, Bdate TEXT, Relationship TEXT,
 PRIMARY KEY (Essn, Dependent_name),
 FOREIGN KEY (Essn) REFERENCES EMPLOYEE(Ssn) ON DELETE CASCADE
);
